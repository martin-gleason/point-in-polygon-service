def test_progress_is_called_once_per_row_with_a_running_count(lookup):
    seen = []
    rows = [
        {"latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)},
        {"latitude": "N/A", "longitude": "N/A"},
        {"latitude": str(OUTSIDE_LAT), "longitude": str(OUTSIDE_LON)},
    ]
    def record(rows_done: int, last_status: str) -> None:
        seen.append((rows_done, last_status))

    run(rows, mapping=POINT_MAPPING, lookup=lookup, progress=record)

    assert seen == [
        (1, STATUS_MATCHED),
        (2, STATUS_ERROR),
        (3, STATUS_OUTSIDE),
    ]


def test_results_stream_lazily(lookup):
    # run_batch must yield as it goes, not buffer the whole source: a 50,000-row
    # workbook has to be writable row by row.
    produced = []

    def rows():
        for index in range(3):
            produced.append(index)
            yield {"latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)}

    stream = run_batch(
        rows(), mapping=POINT_MAPPING, lookup=lookup, layer_id="squares"
    )
    first = next(stream)
    assert first.status == STATUS_MATCHED
    assert produced == [0], "the whole source was consumed to produce one result"


# ---- rate limiting (with an injected fake clock; no real sleeping) ----

class FakeClock:
    """A monotonic clock the test drives by hand. `sleep` advances it, so the
    limiter's own bookkeeping sees time passing exactly as it would in reality —
    without the test spending a single real second."""

    def __init__(self):
        self.now = 1000.0
        self.sleeps: list[float] = []

    def __call__(self) -> float:
        return self.now

    def sleep(self, seconds: float) -> None:
        self.sleeps.append(seconds)
        self.now += seconds

    def advance(self, seconds: float) -> None:
        self.now += seconds


class CountingRateLimiter:
    """Records `wait()` calls without any timing behaviour."""

    def __init__(self):
        self.calls = 0

    def wait(self) -> None:
        self.calls += 1


def test_rate_limiter_first_call_does_not_wait():
    clock = FakeClock()
    limiter = RateLimiter(1.0, sleep=clock.sleep, clock=clock)
    limiter.wait()
    assert clock.sleeps == []


def test_rate_limiter_sleeps_the_remaining_interval():
    clock = FakeClock()
    limiter = RateLimiter(1.0, sleep=clock.sleep, clock=clock)

    limiter.wait()          # t=1000.0, no wait
    clock.advance(0.25)     # the geocode call took a quarter second
    limiter.wait()          # must sleep the remaining 0.75

    assert clock.sleeps == [pytest.approx(0.75)]
    assert clock.now == pytest.approx(1001.0)


def test_rate_limiter_does_not_sleep_when_the_interval_already_passed():
    clock = FakeClock()
    limiter = RateLimiter(1.0, sleep=clock.sleep, clock=clock)

    limiter.wait()
    clock.advance(5.0)      # a slow provider already ate the budget
    limiter.wait()

    assert clock.sleeps == []


def test_rate_limiter_holds_the_interval_across_many_calls():
    clock = FakeClock()
    limiter = RateLimiter(1.0, sleep=clock.sleep, clock=clock)

    stamps = []
    for _ in range(4):
        limiter.wait()
        stamps.append(clock.now)
        clock.advance(0.1)  # each call takes 0.1s of real work

    gaps = [b - a for a, b in zip(stamps, stamps[1:])]
    assert gaps == [pytest.approx(1.0)] * 3
    assert sum(clock.sleeps) == pytest.approx(2.7)  # 3 x (1.0 - 0.1)


def test_zero_interval_never_sleeps():
    clock = FakeClock()
    limiter = RateLimiter(0, sleep=clock.sleep, clock=clock)
    for _ in range(5):
        limiter.wait()
    assert clock.sleeps == []


def test_negative_interval_is_rejected():
    with pytest.raises(ValueError, match="min_interval_seconds"):
        RateLimiter(-1.0)


def test_run_batch_waits_before_every_geocode_call(lookup):
    clock = FakeClock()
    limiter = RateLimiter(1.0, sleep=clock.sleep, clock=clock)
    geocoder = StubGeocoder([a_hit(), a_hit(), a_hit()])
    rows = [{"site_address": f"{n} Test St"} for n in (1, 2, 3)]

    results = run(
        rows,
        mapping=ADDRESS_MAPPING,
        lookup=lookup,
        geocoder=geocoder,
        rate_limiter=limiter,
    )

    assert [r.status for r in results] == [STATUS_MATCHED] * 3
    # Three geocodes, two enforced gaps of the full interval (the first is free).
    assert clock.sleeps == [pytest.approx(1.0), pytest.approx(1.0)]


def test_rate_limiter_still_applies_to_failing_geocode_calls(lookup):
    # A provider that errors must not become a way to hammer it faster.
    clock = FakeClock()
    limiter = RateLimiter(2.0, sleep=clock.sleep, clock=clock)
    geocoder = StubGeocoder([GeocoderUnavailable("down"), GeocoderUnavailable("down")])
    rows = [{"site_address": "1 Test St"}, {"site_address": "2 Test St"}]

    results = run(
        rows,
        mapping=ADDRESS_MAPPING,
        lookup=lookup,
        geocoder=geocoder,
        rate_limiter=limiter,
    )

    assert [r.status for r in results] == [STATUS_ERROR, STATUS_ERROR]
    assert clock.sleeps == [pytest.approx(2.0)]
