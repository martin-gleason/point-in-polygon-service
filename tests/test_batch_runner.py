# ---- whole-run failures happen before row 1 ----

def test_missing_geocoder_raises_before_any_row_is_processed(lookup):
    # The rows iterator must be untouched: failing on row 1 of 2,000 after a
    # thirty-minute rate-limited wait is the failure mode this guards.
    consumed = []

    def rows():
        for index in range(3):
            consumed.append(index)
            yield {"site_address": SECRET_ADDRESS}

    with pytest.raises(BatchError, match="geocoder"):
        run_batch(
            rows(), mapping=ADDRESS_MAPPING, lookup=lookup, layer_id="squares"
        )

    assert consumed == [], "rows were consumed before the precondition failed"


def test_unknown_layer_raises_before_any_row_is_processed(lookup):
    consumed = []

    def rows():
        consumed.append(1)
        yield {"latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)}

    with pytest.raises(BatchError, match="unknown layer"):
        run_batch(
            rows(), mapping=POINT_MAPPING, lookup=lookup, layer_id="no_such_layer"
        )

    assert consumed == []


def test_missing_mapped_column_is_a_whole_run_failure(lookup):
    # A column the file simply does not have is a mapping mistake: stop, rather
    # than emit a file of identical per-row errors.
    rows = [{"lat": str(INSIDE_LAT), "lon": str(INSIDE_LON)}]
    with pytest.raises(BatchError) as raised:
        run(rows, mapping=POINT_MAPPING, lookup=lookup)

    message = str(raised.value)
    # Both the columns that are missing and the ones the source actually has —
    # the same wording sources.validate_column_mapping uses, so one mistake
    # reads the same whichever layer catches it.
    assert "not found" in message
    assert "'latitude'" in message and "'longitude'" in message
    assert "'lat'" in message and "'lon'" in message


