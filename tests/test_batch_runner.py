"""F7-T3 — tests for the batch engine.

Everything runs against a tiny synthetic GeoPackage (two squares in EPSG:3435,
the same idiom as tests/test_lookup.py) and a stub geocoder object. There is no
network here at all: the lat/lon path never has one, and the address path is
served by a stub whose behaviour each test dictates. That is the point — the
suite proves the engine's contract, not a provider's.
"""
import geopandas as gpd
import pytest
from pyproj import Transformer
from shapely.geometry import box

from app.batch import (
    STATUS_ERROR,
    STATUS_MATCHED,
    STATUS_NO_GEOCODE,
    STATUS_OUTSIDE,
    BatchError,
    ColumnMapping,
)
from app.batch.runner import RateLimiter, run_batch
from app.config import AppConfig, LayerConfig
from app.geocoding.base import GeocodeResult, GeocoderUnavailable
from app.lookup import PolygonLookup

# One square in EPSG:3435 (Illinois State Plane East, ftUS). Query points are
# generated by inverting known planar points back to WGS84, so the test never
# depends on the projection's sign conventions.
CX, CY = 1_100_000.0, 1_900_000.0
HALF = 2_000.0
_INV = Transformer.from_crs("EPSG:3435", "EPSG:4326", always_xy=True)

INSIDE_LON, INSIDE_LAT = _INV.transform(CX, CY)
OUTSIDE_LON, OUTSIDE_LAT = _INV.transform(CX + 50 * HALF, CY)

# A stand-in for a real caseload address. Every PII assertion checks that this
# exact string never reaches a result field it does not belong in.
SECRET_ADDRESS = "1428 N Elm St Apt 3B, Chicago, IL 60622"


@pytest.fixture
def lookup(tmp_path) -> PolygonLookup:
    frame = gpd.GeoDataFrame(
        {"name": ["alpha"], "code": ["A"]},
        geometry=[box(CX - HALF, CY - HALF, CX + HALF, CY + HALF)],
        crs="EPSG:3435",
    )
    gpkg = tmp_path / "squares.gpkg"
    frame.to_file(gpkg, layer="squares", driver="GPKG")
    config = AppConfig(
        layers={
            "squares": LayerConfig(
                id="squares",
                name="Test Squares",
                path=gpkg,
                layer="squares",
                attributes=("name", "code"),
                source="synthetic test fixture",
            )
        }
    )
    return PolygonLookup(config)


class StubGeocoder:
    """A scripted geocoder: hands back queued outcomes, records every query.

    A queued item that is an exception instance is raised instead of returned,
    which is how the "provider dies mid-run" tests are written.
    """

    def __init__(self, outcomes, name="stub"):
        self.name = name
        self._outcomes = list(outcomes)
        self.queries: list[str] = []

    def geocode(self, address: str) -> GeocodeResult:
        self.queries.append(address)
        outcome = self._outcomes.pop(0)
        if isinstance(outcome, Exception):
            raise outcome
        return outcome


def a_hit(query=SECRET_ADDRESS, lon=INSIDE_LON, lat=INSIDE_LAT) -> GeocodeResult:
    return GeocodeResult(
        query=query,
        matched=True,
        provider="stub",
        point=(lon, lat),
        score=95.0,
        matched_address="1428 N ELM ST, CHICAGO, IL, 60622",
    )


ADDRESS_MAPPING = ColumnMapping(address="site_address")
POINT_MAPPING = ColumnMapping(lat="latitude", lon="longitude")


def run(rows, **kwargs):
    return list(run_batch(rows, layer_id="squares", **kwargs))


# ---- the lat/lon path (no geocoder, no network, ever) ----

def test_coordinates_inside_polygon_match(lookup):
    rows = [{"case": "1", "latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)}]
    results = run(rows, mapping=POINT_MAPPING, lookup=lookup)

    assert len(results) == 1
    result = results[0]
    assert result.status == STATUS_MATCHED
    assert result.ok is True
    assert result.feature == {"name": "alpha", "code": "A"}
    assert result.lon == pytest.approx(INSIDE_LON)
    assert result.lat == pytest.approx(INSIDE_LAT)
    # Nothing was geocoded, so there is no provider or score to report.
    assert result.provider is None
    assert result.score is None


def test_coordinate_path_never_touches_the_geocoder(lookup):
    # Passing a geocoder that would explode proves the offline path never calls
    # it — this is the "network severed" guarantee, asserted rather than assumed.
    exploding = StubGeocoder([AssertionError("geocoder must not be called")])
    rows = [{"latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)}]
    results = run(rows, mapping=POINT_MAPPING, lookup=lookup, geocoder=exploding)

    assert results[0].status == STATUS_MATCHED
    assert exploding.queries == []


def test_coordinate_path_never_uses_the_rate_limiter(lookup):
    limiter = CountingRateLimiter()
    rows = [{"latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)}] * 3
    run(rows, mapping=POINT_MAPPING, lookup=lookup, rate_limiter=limiter)
    assert limiter.calls == 0


def test_coordinates_outside_all_polygons(lookup):
    rows = [{"latitude": str(OUTSIDE_LAT), "longitude": str(OUTSIDE_LON)}]
    result = run(rows, mapping=POINT_MAPPING, lookup=lookup)[0]

    assert result.status == STATUS_OUTSIDE
    assert result.ok is False
    assert result.reason == "point_outside_all_polygons"
    assert result.feature is None
    # The point itself is still reported so the operator can see what was tried.
    assert result.lon == pytest.approx(OUTSIDE_LON)


@pytest.mark.parametrize(
    "latitude,longitude",
    [
        ("N/A", "-87.6"),          # a human's "no data" marker
        ("", "-87.6"),             # blank cell
        ("   ", "-87.6"),          # whitespace-only cell
        ("41.88", ""),             # only one of the pair is missing
        ("41,88", "-87.6"),        # European decimal comma
        ("nan", "-87.6"),          # parses as a float but is not a coordinate
    ],
)
def test_unusable_coordinates_are_error_rows(lookup, latitude, longitude):
    rows = [{"latitude": latitude, "longitude": longitude}]
    result = run(rows, mapping=POINT_MAPPING, lookup=lookup)[0]

    assert result.status == STATUS_ERROR
    assert result.reason
    assert result.feature is None


def test_out_of_range_coordinates_are_error_rows(lookup):
    # Latitude 91 is a real number but not a real latitude: the engine raises
    # InvalidCoordinateError, which must degrade to one flagged row.
    rows = [{"latitude": "91.0", "longitude": "-87.6"}]
    result = run(rows, mapping=POINT_MAPPING, lookup=lookup)[0]

    assert result.status == STATUS_ERROR
    assert "WGS84" in result.reason


def test_bad_coordinate_row_does_not_abort_the_run(lookup):
    rows = [
        {"case": "1", "latitude": str(INSIDE_LAT), "longitude": str(INSIDE_LON)},
        {"case": "2", "latitude": "N/A", "longitude": "N/A"},
        {"case": "3", "latitude": str(OUTSIDE_LAT), "longitude": str(OUTSIDE_LON)},
    ]
    results = run(rows, mapping=POINT_MAPPING, lookup=lookup)

    assert [r.status for r in results] == [STATUS_MATCHED, STATUS_ERROR, STATUS_OUTSIDE]
    assert [r.row["case"] for r in results] == ["1", "2", "3"]


# ---- the geocoding path ----

def test_geocoded_row_matches(lookup):
    geocoder = StubGeocoder([a_hit()])
    rows = [{"site_address": SECRET_ADDRESS}]
    result = run(rows, mapping=ADDRESS_MAPPING, lookup=lookup, geocoder=geocoder)[0]

    assert result.status == STATUS_MATCHED
    assert result.feature == {"name": "alpha", "code": "A"}
    assert result.matched_address == "1428 N ELM ST, CHICAGO, IL, 60622"
    assert result.score == 95.0
    assert result.provider == "stub"
    assert geocoder.queries == [SECRET_ADDRESS]


def test_geocoder_no_match_is_no_geocode(lookup):
    geocoder = StubGeocoder([GeocodeResult.no_match(SECRET_ADDRESS, "stub")])
    rows = [{"site_address": SECRET_ADDRESS}]
    result = run(rows, mapping=ADDRESS_MAPPING, lookup=lookup, geocoder=geocoder)[0]

    assert result.status == STATUS_NO_GEOCODE
    assert result.provider == "stub"
    assert result.lon is None and result.lat is None
    assert result.feature is None


def test_geocoded_point_outside_all_polygons(lookup):
    geocoder = StubGeocoder([a_hit(lon=OUTSIDE_LON, lat=OUTSIDE_LAT)])
    rows = [{"site_address": SECRET_ADDRESS}]
    result = run(rows, mapping=ADDRESS_MAPPING, lookup=lookup, geocoder=geocoder)[0]

    assert result.status == STATUS_OUTSIDE
    assert result.reason == "point_outside_all_polygons"
    # A geocoded-but-outside row still carries the geocode, which is exactly the
    # evidence an operator needs to decide whether the layer or the address is
    # at fault.
    assert result.matched_address == "1428 N ELM ST, CHICAGO, IL, 60622"
    assert result.provider == "stub"


def test_blank_address_is_an_error_and_costs_no_request(lookup):
    geocoder = StubGeocoder([a_hit()])
    limiter = CountingRateLimiter()
    rows = [{"site_address": "   "}, {"site_address": SECRET_ADDRESS}]
    results = run(
        rows,
        mapping=ADDRESS_MAPPING,
        lookup=lookup,
        geocoder=geocoder,
        rate_limiter=limiter,
    )

    assert [r.status for r in results] == [STATUS_ERROR, STATUS_MATCHED]
    # The blank row consumed neither a provider request nor a rate-limit slot.
    assert geocoder.queries == [SECRET_ADDRESS]
    assert limiter.calls == 1


def test_geocoder_unavailable_mid_run_does_not_stop_the_run(lookup):
    geocoder = StubGeocoder(
        [
            a_hit(),
            GeocoderUnavailable("connect timeout to https://example.test/geocode"),
            a_hit(),
        ]
    )
    rows = [
        {"case": "1", "site_address": "121 N La Salle St"},
        {"case": "2", "site_address": SECRET_ADDRESS},
        {"case": "3", "site_address": "233 S Wacker Dr"},
    ]
    results = run(rows, mapping=ADDRESS_MAPPING, lookup=lookup, geocoder=geocoder)

    assert [r.status for r in results] == [STATUS_MATCHED, STATUS_ERROR, STATUS_MATCHED]
    assert results[1].reason == "geocoder unavailable"
    # Crucially: rows 3 was still attempted after the failure.
    assert len(geocoder.queries) == 3


def test_unexpected_provider_exception_becomes_one_error_row(lookup):
    # A provider bug (not a GeocoderUnavailable) must not take the run with it.
    geocoder = StubGeocoder([KeyError("candidates"), a_hit()])
    rows = [{"site_address": SECRET_ADDRESS}, {"site_address": "121 N La Salle St"}]
    results = run(rows, mapping=ADDRESS_MAPPING, lookup=lookup, geocoder=geocoder)

    assert [r.status for r in results] == [STATUS_ERROR, STATUS_MATCHED]
    assert "KeyError" in results[0].reason


